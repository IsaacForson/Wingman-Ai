"""
Wingman AI - Session Exporter
Export sessions and data in multiple formats (JSON, PDF, TXT)
"""

import json
from datetime import datetime
from typing import Dict, Any, List, Optional
from pathlib import Path
from dataclasses import dataclass, asdict
from loguru import logger
import io


@dataclass
class ExportData:
    """Data structure for export"""
    title: str
    created_at: str
    export_type: str  # 'session', 'transcript', 'analytics', 'settings'
    content: Dict[str, Any]
    metadata: Dict[str, Any]


class SessionExporter:
    """
    Export sessions and data in multiple formats
    Supports JSON, TXT, and PDF (via HTML)
    """
    
    def __init__(self, export_dir: str = "exports"):
        self._export_dir = Path(export_dir)
        self._export_dir.mkdir(parents=True, exist_ok=True)
    
    async def export_to_json(
        self,
        data: ExportData,
        filename: Optional[str] = None
    ) -> str:
        """
        Export data to JSON format
        
        Args:
            data: Export data
            filename: Optional filename
            
        Returns:
            Path to exported file
        """
        if not filename:
            filename = f"{data.export_type}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
        
        filepath = self._export_dir / filename
        
        export_content = {
            "title": data.title,
            "created_at": data.created_at,
            "export_type": data.export_type,
            "exported_at": datetime.now().isoformat(),
            "content": data.content,
            "metadata": data.metadata
        }
        
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(export_content, f, indent=2, ensure_ascii=False)
        
        logger.info(f"Exported JSON to {filepath}")
        return str(filepath)
    
    async def export_to_txt(
        self,
        data: ExportData,
        filename: Optional[str] = None
    ) -> str:
        """
        Export data to plain text format
        
        Args:
            data: Export data
            filename: Optional filename
            
        Returns:
            Path to exported file
        """
        if not filename:
            filename = f"{data.export_type}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt"
        
        filepath = self._export_dir / filename
        
        lines = []
        lines.append("=" * 60)
        lines.append(f"WINGMAN AI - {data.title.upper()}")
        lines.append("=" * 60)
        lines.append(f"Created: {data.created_at}")
        lines.append(f"Exported: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        lines.append(f"Type: {data.export_type}")
        lines.append("")
        lines.append("-" * 60)
        lines.append("")
        
        # Format content based on type
        if data.export_type == "transcript":
            lines.extend(self._format_transcript_txt(data.content))
        elif data.export_type == "session":
            lines.extend(self._format_session_txt(data.content))
        elif data.export_type == "analytics":
            lines.extend(self._format_analytics_txt(data.content))
        elif data.export_type == "meeting":
            lines.extend(self._format_meeting_txt(data.content))
        else:
            lines.extend(self._format_generic_txt(data.content))
        
        lines.append("")
        lines.append("-" * 60)
        lines.append("Generated by Wingman AI")
        lines.append("=" * 60)
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines))
        
        logger.info(f"Exported TXT to {filepath}")
        return str(filepath)
    
    async def export_to_html(
        self,
        data: ExportData,
        filename: Optional[str] = None
    ) -> str:
        """
        Export data to HTML format (can be converted to PDF)
        
        Args:
            data: Export data
            filename: Optional filename
            
        Returns:
            Path to exported file
        """
        if not filename:
            filename = f"{data.export_type}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.html"
        
        filepath = self._export_dir / filename
        
        html_content = self._generate_html(data)
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(html_content)
        
        logger.info(f"Exported HTML to {filepath}")
        return str(filepath)
    
    def _format_transcript_txt(self, content: Dict[str, Any]) -> List[str]:
        """Format transcript for text export"""
        lines = []
        lines.append("TRANSCRIPT")
        lines.append("")
        
        entries = content.get("entries", [])
        for entry in entries:
            timestamp = entry.get("timestamp", "00:00")
            speaker = entry.get("speaker", "Unknown")
            text = entry.get("text", "")
            
            lines.append(f"[{timestamp}] {speaker}:")
            lines.append(f"  {text}")
            lines.append("")
        
        return lines
    
    def _format_session_txt(self, content: Dict[str, Any]) -> List[str]:
        """Format session for text export"""
        lines = []
        lines.append("SESSION SUMMARY")
        lines.append("")
        
        # Questions and answers
        qa_pairs = content.get("qa_pairs", [])
        for i, qa in enumerate(qa_pairs, 1):
            lines.append(f"Q{i}: {qa.get('question', 'N/A')}")
            lines.append(f"A{i}: {qa.get('answer', 'N/A')}")
            lines.append(f"    Source: {qa.get('source', 'N/A')}")
            lines.append(f"    Mode: {qa.get('mode', 'N/A')}")
            lines.append("")
        
        # Statistics
        stats = content.get("statistics", {})
        if stats:
            lines.append("STATISTICS")
            lines.append(f"  Total Questions: {stats.get('total_questions', 0)}")
            lines.append(f"  Total Answers: {stats.get('total_answers', 0)}")
            lines.append(f"  Duration: {stats.get('duration_minutes', 0)} minutes")
        
        return lines
    
    def _format_analytics_txt(self, content: Dict[str, Any]) -> List[str]:
        """Format analytics for text export"""
        lines = []
        lines.append("ANALYTICS REPORT")
        lines.append("")
        
        # Usage stats
        usage = content.get("usage", {})
        lines.append("Usage Statistics:")
        lines.append(f"  Total Questions: {usage.get('total_questions', 0)}")
        lines.append(f"  Total Sessions: {usage.get('total_sessions', 0)}")
        lines.append(f"  Total Time: {usage.get('total_time_hours', 0)} hours")
        lines.append("")
        
        # By mode
        by_mode = content.get("by_mode", {})
        if by_mode:
            lines.append("Questions by Mode:")
            for mode, count in by_mode.items():
                lines.append(f"  {mode.capitalize()}: {count}")
            lines.append("")
        
        # Performance
        performance = content.get("performance", {})
        if performance:
            lines.append("Performance Metrics:")
            lines.append(f"  Average Response Time: {performance.get('avg_response_time', 'N/A')}s")
            lines.append(f"  Success Rate: {performance.get('success_rate', 'N/A')}%")
        
        return lines
    
    def _format_meeting_txt(self, content: Dict[str, Any]) -> List[str]:
        """Format meeting summary for text export"""
        lines = []
        lines.append("MEETING SUMMARY")
        lines.append("")
        
        # Participants
        participants = content.get("participants", [])
        if participants:
            lines.append("Participants:")
            for p in participants:
                lines.append(f"  - {p.get('name', 'Unknown')} ({p.get('speaking_time', 0)} min)")
            lines.append("")
        
        # Key Points
        key_points = content.get("key_points", [])
        if key_points:
            lines.append("Key Points:")
            for point in key_points:
                lines.append(f"  • {point}")
            lines.append("")
        
        # Action Items
        action_items = content.get("action_items", [])
        if action_items:
            lines.append("Action Items:")
            for item in action_items:
                assignee = item.get('assignee', 'Unassigned')
                text = item.get('text', '')
                priority = item.get('priority', 'normal')
                lines.append(f"  [{priority.upper()}] {text} - {assignee}")
            lines.append("")
        
        # Transcript summary
        summary = content.get("summary", "")
        if summary:
            lines.append("Summary:")
            lines.append(f"  {summary}")
        
        return lines
    
    def _format_generic_txt(self, content: Dict[str, Any]) -> List[str]:
        """Format generic content for text export"""
        lines = []
        
        def format_dict(d: Dict, indent: int = 0):
            result = []
            prefix = "  " * indent
            for key, value in d.items():
                if isinstance(value, dict):
                    result.append(f"{prefix}{key}:")
                    result.extend(format_dict(value, indent + 1))
                elif isinstance(value, list):
                    result.append(f"{prefix}{key}:")
                    for item in value:
                        if isinstance(item, dict):
                            result.extend(format_dict(item, indent + 1))
                        else:
                            result.append(f"{prefix}  - {item}")
                else:
                    result.append(f"{prefix}{key}: {value}")
            return result
        
        lines.extend(format_dict(content))
        return lines
    
