    def _content_to_html(self, content: Dict[str, Any], export_type: str) -> str:
        """Convert content to HTML based on type"""
        
        if export_type == "transcript":
            return self._transcript_to_html(content)
        elif export_type == "session":
            return self._session_to_html(content)
        elif export_type == "meeting":
            return self._meeting_to_html(content)
        elif export_type == "analytics":
            return self._analytics_to_html(content)
        else:
            return self._generic_to_html(content)
    
    def _transcript_to_html(self, content: Dict) -> str:
        """Convert transcript to HTML"""
        entries = content.get("entries", [])
        
        entries_html = ""
        for entry in entries:
            entries_html += f"""
            <div class="transcript-entry">
                <span class="timestamp">[{entry.get('timestamp', '00:00')}]</span>
                <span class="speaker">{entry.get('speaker', 'Unknown')}:</span>
                <span>{entry.get('text', '')}</span>
            </div>
            """
        
        return f"""
        <div class="section">
            <h2>Transcript</h2>
            {entries_html}
        </div>
        """
    
    def _session_to_html(self, content: Dict) -> str:
        """Convert session to HTML"""
        qa_pairs = content.get("qa_pairs", [])
        stats = content.get("statistics", {})
        
        qa_html = ""
        for i, qa in enumerate(qa_pairs, 1):
            qa_html += f"""
            <div class="qa-item">
                <div class="question">Q{i}: {qa.get('question', 'N/A')}</div>
                <div class="answer">{qa.get('answer', 'N/A')}</div>
            </div>
            """
        
        stats_html = ""
        if stats:
            stats_html = f"""
            <div class="section">
                <h2>Statistics</h2>
                <span class="stat">Questions: {stats.get('total_questions', 0)}</span>
                <span class="stat">Answers: {stats.get('total_answers', 0)}</span>
                <span class="stat">Duration: {stats.get('duration_minutes', 0)} min</span>
            </div>
            """
        
        return f"""
        <div class="section">
            <h2>Questions & Answers</h2>
            {qa_html}
        </div>
        {stats_html}
        """
    
    def _meeting_to_html(self, content: Dict) -> str:
        """Convert meeting summary to HTML"""
        key_points = content.get("key_points", [])
        action_items = content.get("action_items", [])
        summary = content.get("summary", "")
        
        points_html = "".join(f"<li>{p}</li>" for p in key_points)
        
        actions_html = ""
        for item in action_items:
            priority_class = "high" if item.get('priority') == 'high' else ""
            actions_html += f"""
            <div class="action-item {priority_class}">
                <strong>{item.get('text', '')}</strong><br>
                <small>Assigned to: {item.get('assignee', 'Unassigned')} | Priority: {item.get('priority', 'normal')}</small>
            </div>
            """
        
        return f"""
        <div class="section">
            <h2>Key Points</h2>
            <ul>{points_html}</ul>
        </div>
        <div class="section">
            <h2>Action Items</h2>
            {actions_html}
        </div>
        <div class="section">
            <h2>Summary</h2>
            <p>{summary}</p>
        </div>
        """
    
    def _analytics_to_html(self, content: Dict) -> str:
        """Convert analytics to HTML"""
        usage = content.get("usage", {})
        
        return f"""
        <div class="section">
            <h2>Usage Statistics</h2>
            <span class="stat">Questions: {usage.get('total_questions', 0)}</span>
            <span class="stat">Sessions: {usage.get('total_sessions', 0)}</span>
            <span class="stat">Time: {usage.get('total_time_hours', 0)} hours</span>
        </div>
        """
    
    def _generic_to_html(self, content: Dict) -> str:
        """Convert generic content to HTML"""
        return f"""
        <div class="section">
            <h2>Content</h2>
            <pre>{json.dumps(content, indent=2)}</pre>
        </div>
        """
    
